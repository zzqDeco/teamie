// Command generate builds Chat's exact Unicode Emoji allowlist from vendored data.
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"
	"strings"
)

const sourceSHA256 = "1d8a944f88d7952f7ef7c5167fef3c67995bcae24543949710231b03a201acda"

func main() {
	input := flag.String("data", "tools/unicode-emoji/data/17.0.0/emoji-test.txt", "vendored Unicode data")
	output := flag.String("out", "services/chat/internal/domain/reaction_emoji_generated.go", "generated Go allowlist")
	check := flag.Bool("check", false, "verify the checked-in output without writing")
	flag.Parse()
	if err := run(*input, *output, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(input, output string, check bool) error {
	data, err := os.ReadFile(input)
	if err != nil {
		return err
	}
	if fmt.Sprintf("%x", sha256.Sum256(data)) != sourceSHA256 || !bytes.Contains(data, []byte("# Version: 17.0\n")) {
		return fmt.Errorf("unexpected Unicode Emoji 17.0 data or checksum")
	}
	set := make(map[string]struct{})
	scanner := bufio.NewScanner(bytes.NewReader(data))
	for scanner.Scan() {
		line := scanner.Text()
		points, rest, ok := strings.Cut(line, ";")
		if !ok || strings.TrimSpace(strings.SplitN(rest, "#", 2)[0]) != "fully-qualified" {
			continue
		}
		var sequence strings.Builder
		for _, point := range strings.Fields(points) {
			value, err := strconv.ParseInt(point, 16, 32)
			if err != nil {
				return err
			}
			sequence.WriteRune(rune(value))
		}
		set[sequence.String()] = struct{}{}
	}
	if err := scanner.Err(); err != nil {
		return err
	}
	if len(set) != 3944 {
		return fmt.Errorf("expected 3944 fully-qualified sequences, got %d", len(set))
	}
	sequences := make([]string, 0, len(set))
	for sequence := range set {
		sequences = append(sequences, sequence)
	}
	sort.Strings(sequences)
	var source bytes.Buffer
	fmt.Fprintln(&source, "// Code generated by tools/unicode-emoji/generate.go; DO NOT EDIT.")
	fmt.Fprintln(&source, "// Unicode Emoji 17.0, fully-qualified sequences only.")
	fmt.Fprintf(&source, "// Source SHA-256: %s\n", sourceSHA256)
	fmt.Fprintln(&source, "// Unicode data license: tools/unicode-emoji/data/LICENSE.txt.")
	fmt.Fprintln(&source, "package domain")
	fmt.Fprintln(&source, "const reactionEmojiVersion = \"17.0\"")
	fmt.Fprintln(&source, "var reactionEmojiSequences = []string{")
	for _, sequence := range sequences {
		fmt.Fprintf(&source, "%s,\n", strconv.QuoteToASCII(sequence))
	}
	fmt.Fprintln(&source, "}")
	generated, err := format.Source(source.Bytes())
	if err != nil {
		return err
	}
	if check {
		current, err := os.ReadFile(output)
		if err != nil {
			return err
		}
		if !bytes.Equal(current, generated) {
			return fmt.Errorf("Unicode emoji allowlist is stale; run go run tools/unicode-emoji/generate.go")
		}
		return nil
	}
	return os.WriteFile(output, generated, 0644)
}
