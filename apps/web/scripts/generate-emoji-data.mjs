#!/usr/bin/env node
// Generates src/chat/emoji-data.generated.ts from the vendored, pinned
// Unicode Emoji 17.0 data used by Chat's reaction allowlist
// (tools/unicode-emoji). Run from apps/web:
//   node scripts/generate-emoji-data.mjs          # write
//   node scripts/generate-emoji-data.mjs --check  # verify the checked-in file
/* global process, console */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, "../../../tools/unicode-emoji/data/17.0.0/emoji-test.txt");
const output = join(here, "../src/chat/emoji-data.generated.ts");
const SHA256 = "1d8a944f88d7952f7ef7c5167fef3c67995bcae24543949710231b03a201acda";
const EXPECTED = 3944;
const LABELS = {
  "Smileys & Emotion": ["smileys", "笑脸与情感"],
  "People & Body": ["people", "人物与身体"],
  "Animals & Nature": ["nature", "动物与自然"],
  "Food & Drink": ["food", "食物与饮料"],
  "Travel & Places": ["travel", "旅行与地点"],
  Activities: ["activities", "活动"],
  Objects: ["objects", "物品"],
  Symbols: ["symbols", "符号"],
  Flags: ["flags", "旗帜"],
};
const SKIN_TONE = /[\u{1F3FB}-\u{1F3FF}]/u;

const data = readFileSync(source);
if (createHash("sha256").update(data).digest("hex") !== SHA256)
  throw new Error("unexpected Unicode Emoji 17.0 data or checksum");
const groups = [];
const variants = [];
let group = null;
let count = 0;
for (const line of data.toString("utf8").split("\n")) {
  const heading = /^# group: (.+)$/.exec(line);
  if (heading) {
    const label = LABELS[heading[1].trim()];
    group = label ? { id: label[0], label: label[1], entries: [] } : null;
    if (group) groups.push(group);
    continue;
  }
  const match = /^([0-9A-F ]+?)\s*; fully-qualified\s*# \S+ E\d+\.\d+ (.+)$/.exec(line);
  if (!match) continue;
  const emoji = String.fromCodePoint(...match[1].trim().split(/\s+/).map((p) => parseInt(p, 16)));
  count++;
  if (!group) throw new Error(`fully-qualified entry outside a known group: ${line}`);
  if (SKIN_TONE.test(emoji)) variants.push(emoji);
  else group.entries.push([emoji, match[2].trim()]);
}
if (count !== EXPECTED) throw new Error(`expected ${EXPECTED} fully-qualified sequences, got ${count}`);

const lines = [
  "// Generated by scripts/generate-emoji-data.mjs from the pinned Unicode Emoji",
  "// 17.0 emoji-test.txt (tools/unicode-emoji). Do not edit by hand.",
  `export const EMOJI_SOURCE_SHA256 = "${SHA256}";`,
  `export const FULLY_QUALIFIED_COUNT = ${EXPECTED};`,
  "/** Picker groups: [emoji, CLDR English name] pairs, skin-tone variants excluded. */",
  "export const EMOJI_GROUPS: ReadonlyArray<{ id: string; label: string; entries: ReadonlyArray<readonly [string, string]> }> = [",
  ...groups.map(
    (g) => `  { id: ${JSON.stringify(g.id)}, label: ${JSON.stringify(g.label)}, entries: ${JSON.stringify(g.entries)} },`,
  ),
  "];",
  "/** Remaining fully-qualified sequences (skin-tone variants), space separated. */",
  `export const EMOJI_VARIANTS = ${JSON.stringify(variants.join(" "))};`,
  "",
];
const text = lines.join("\n");
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== text) {
    console.error("emoji-data.generated.ts is out of date; run node scripts/generate-emoji-data.mjs");
    process.exit(1);
  }
} else {
  writeFileSync(output, text);
}
