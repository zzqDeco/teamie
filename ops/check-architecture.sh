#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${ROOT_DIR}"

# 1. Contract sync gate
bash ops/codegen.sh --check

# 2. Generated code purity gate: every .go file in contracts/gen/ must be tool-generated
while IFS= read -r -d '' f; do
  if [[ "$(basename "${f}")" == "k-consts.go" ]] && grep -q 'KitexUnusedProtection' "${f}"; then
    continue
  fi
  if ! head -n 1 "${f}" | grep -q '^// Code generated by '; then
    echo "Handwritten .go file found in contracts/gen/: ${f}" >&2
    exit 1
  fi
done < <(find contracts/gen -type f -name '*.go' -print0)

# 3. IM independence gate: services/{identity,chat,realtime} and pkg must never depend on eino, contracts/gen/agent, or services/agent-*
for svc in pkg services/identity services/chat services/realtime; do
  deps="$(cd "${svc}" && go list -deps ./...)"
  if printf '%s\n' "${deps}" | grep -E '(github\.com/cloudwego/eino|teamie/contracts/gen/agent|teamie/services/agent-)' >/dev/null; then
    echo "IM independence violation in ${svc}" >&2
    exit 1
  fi
done

# 4. DDD domain layer purity gate: services/*/internal/domain/... must never import hertz, kitex, pgx, eino, contracts/gen, or teamie/
for svc in services/*; do
  if [[ -d "${svc}/internal/domain" ]]; then
    domain_imports="$(cd "${svc}" && go list -f '{{join .Imports "\n"}}' ./internal/domain/...)"
    if printf '%s\n' "${domain_imports}" | grep -E '(hertz|kitex|pgx|eino|contracts/gen|teamie/)' >/dev/null; then
      echo "DDD domain layer purity violation in ${svc}/internal/domain" >&2
      exit 1
    fi
  fi
done

# 5. DDD app layer purity gate: services/*/internal/app/... must never import adapter, infra, hertz, kitex, pgx, eino, contracts/gen, or syscall
for svc in services/*; do
  if [[ -d "${svc}/internal/app" ]]; then
    app_imports="$(cd "${svc}" && go list -f '{{join .Imports "\n"}}' ./internal/app/...)"
    if printf '%s\n' "${app_imports}" | grep -E '(internal/adapter|internal/infra|hertz|kitex|pgx|eino|contracts/gen|^syscall$)' >/dev/null; then
      echo "DDD app layer purity violation in ${svc}/internal/app" >&2
      exit 1
    fi
  fi
done

# 6. Agent Runtime infra/eino & infra/pg isolation gate:
# - non-test files in infra/eino must not import pgx or infra/pg
# - infra/pg must not import github.com/cloudwego/eino
eino_imports="$(cd services/agent-runtime && go list -f '{{join .Imports "\n"}}' ./internal/infra/eino)"
if printf '%s\n' "${eino_imports}" | grep -E '(github\.com/jackc/pgx|teamie/services/agent-runtime/internal/infra/pg)' >/dev/null; then
  echo "infra/eino must not import github.com/jackc/pgx or internal/infra/pg directly; use domain.RuntimeRepository" >&2
  exit 1
fi
runtime_pg_imports="$(cd services/agent-runtime && go list -f '{{join .Imports "\n"}}' ./internal/infra/pg/...)"
if printf '%s\n' "${runtime_pg_imports}" | grep -E 'github\.com/cloudwego/eino' >/dev/null; then
  echo "infra/pg in services/agent-runtime must not import github.com/cloudwego/eino" >&2
  exit 1
fi

# 7. Shared pkg/ directory structure gate: strictly the 7 packages from Plan Section 1.2
expected_pkg=$'crypto\nhttpx\nimlimits\nimtext\nobservability\npostgres\nrpcx'
actual_pkg="$(find pkg -mindepth 1 -maxdepth 1 -type d -exec basename {} \; | sort)"
if [[ "${actual_pkg}" != "${expected_pkg}" ]]; then
  echo "pkg/ directory mismatch: expected (${expected_pkg}), got (${actual_pkg})" >&2
  exit 1
fi

# 8. Unified PostgreSQL mechanism gate: every service with internal/infra/pg must import teamie/pkg/postgres and never write manual Begin/Commit/Rollback/pg_advisory_xact_lock
for svc in services/*; do
  if [[ -d "${svc}/internal/infra/pg" ]]; then
    pg_imports="$(cd "${svc}" && go list -f '{{join .Imports "\n"}}' ./internal/infra/pg/...)"
    if ! printf '%s\n' "${pg_imports}" | grep -Fx 'teamie/pkg/postgres' >/dev/null; then
      echo "infra/pg in ${svc} must use shared teamie/pkg/postgres mechanism" >&2
      exit 1
    fi
    if grep -rnE '\.(Begin|Commit|Rollback)\(|pg_advisory_xact_lock' "${svc}/internal/infra/pg" >/dev/null; then
      echo "infra/pg in ${svc} must use pkg/postgres WithinTx/Conn/AdvisoryXactLock instead of manual Begin/Commit/Rollback/pg_advisory_xact_lock" >&2
      exit 1
    fi
  fi
done
